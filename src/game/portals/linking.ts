import type { PortalDimension, PortalFrame } from './frame';

// A block traveled in the Nether corresponds to eight in the Overworld.
// Nearby overworld portals may legitimately share a Nether destination.
export const PORTAL_SEARCH_RADIUS: Readonly<Record<PortalDimension, number>> = {
  overworld: 128,
  nether: 16,
};

/** Select the closest existing destination, never the first inserted frame. */
export function findLinkedPortal(
  portals: readonly PortalFrame[],
  dimension: PortalDimension,
  x: number,
  y: number,
  z: number,
): PortalFrame | null {
  const radiusSq = PORTAL_SEARCH_RADIUS[dimension] ** 2;
  let closest: PortalFrame | null = null;
  let bestDistance = Infinity;
  for (const portal of portals) {
    if (portal.dimension !== dimension) continue;
    const dx = portal.x + 0.5 - x;
    const dz = portal.z + 0.5 - z;
    const horizontalDistance = dx * dx + dz * dz;
    if (horizontalDistance > radiusSq) continue;
    const dy = portal.y + 1 - y;
    const distance = horizontalDistance + dy * dy * 0.25;
    if (distance < bestDistance) {
      closest = portal;
      bestDistance = distance;
    }
  }
  return closest;
}

/** Autogenerated landing pads must not carve through a nearby portal. */
export function conflictsWithPortalSite(
  portals: readonly PortalFrame[],
  dimension: PortalDimension,
  centerX: number,
  floorY: number,
  centerZ: number,
): boolean {
  return portals.some(
    (portal) =>
      portal.dimension === dimension &&
      Math.abs(portal.x + 0.5 - centerX) < 6 &&
      Math.abs(portal.z + 0.5 - (centerZ + 0.5)) < 7 &&
      Math.abs(portal.y - floorY) < 5,
  );
}
